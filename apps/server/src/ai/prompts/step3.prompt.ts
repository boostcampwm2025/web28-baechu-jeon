import { Step3CodeSummaryInput } from '../types/ai.types';

export const buildStep3Prompts = ({
  analysisResult,
  project,
  fileContents,
}: Step3CodeSummaryInput) => {
  const systemPrompt = `당신은 전문 소프트웨어 아키텍트입니다.
1단계에서 추천된 **주요 파일**의 소스코드를 보고, 각 파일마다 **코드 설명 문서**를 **마크다운**으로 작성해야 합니다. 이 문서는 "코드 설명" 탭에서 **새로 합류한 개발자나 유지보수 담당자가 코드를 이해하는 데 쓰입니다.**

# 필수 (응답 완성)
- **응답이 아무리 길어도 중간에 끊지 말고**, \`file_summaries\` 배열에 **제공된 모든 파일**에 대한 항목을 **끝까지** 작성한 뒤 응답을 마치세요. 중간에 끊기면 JSON 파싱에 실패합니다.
- **절대** 마지막 파일까지 쓰기 전에 응답을 끝내지 마세요.

# 목표 독자와 목적
- **독자:** 프로젝트에 익숙하지 않은 개발자(온보딩·유지보수).
- **목적:** "이 파일이 왜 있는지", "무엇을 하는지", "어디서 쓰이는지"를 읽고 빠르게 이해할 수 있게 한다. 기술 용어는 괄호로 보충하거나 한 줄로 풀어 쓴다.

# 분석 대상
- 제공된 "주요 파일 소스코드"에 포함된 **모든 파일**에 대해 \`file_summaries\`에 항목을 하나씩 넣으세요.
- 각 파일의 \`file_path\`는 제공된 키(경로)와 **완전히 동일**하게 넣으세요.

# markdown_content 작성 요청
각 파일의 \`markdown_content\`는 **두 부분**으로 구성하고, **영역이 구분되도록** 마크다운을 작성하세요.

- **영역 구분:** \`##\`로 대섹션(파일 개요, 주요 메서드), \`###\`로 메서드/단위별 소제목을 넣으세요. 대섹션 사이에는 구분선 \`---\`을 넣어 가독성을 높이세요. 각 메서드 블록(코드+설명) 전에 \`### 메서드명\` 같은 소제목을 두면 영역이 명확해집니다.

**1) 파일 개요 (상단)**  
- \`## 파일 개요\` 또는 \`## 개요\` 제목을 두고, 그 아래에 내용을 작성하세요.
- 첫 문단: 이 파일이 프로젝트에서 어떤 위치/역할인지 한 문장으로 비유해 설명 (예: "시작점", "중앙 허브", "~를 담당하는 곳" 등).
- **주요 역할:** 제목 아래에, \`*   **역할 이름**: 구체적 설명\` 형태의 불릿 리스트를 2~5개.

**2) 주요 메서드·코드 단위 (하단, 해당 시)**  
- \`---\` 구분선 뒤에 \`## 주요 메서드\` 또는 \`## 주요 코드\` 제목을 두고, 메서드/단위마다 **소제목 → 코드 → 설명** 순으로 반복하세요.
- **파일 전체를 한꺼번에 보여주지 말고**, 메서드/단위별로만 보여주세요.

- **형식 (메서드/단위마다 반복):**
  1. \`### 메서드명\` 또는 \`### 함수명\` 소제목으로 해당 단위를 표시.
  2. **해당 메서드(또는 코드 단위)의 코드만** \`\`\`코드블록\`\`\`으로 제시 (시그니처 + 핵심 구현 일부, **5~8줄** 이내).
  3. **바로 다음 문단**에 그 코드가 무엇을 하는지 한두 문장으로 설명.
  4. 다음 주요 메서드/단위가 있으면 같은 방식으로 반복: (소제목 → 코드 → 설명) → (소제목 → 코드 → 설명) → …

- **예시 구조:**  
  \`## 개요\`  
  (개요 내용)  
  \`---\`  
  \`## 주요 메서드\`  
  \`### createProject\`  
  \`\`\`  
  [코드만]  
  \`\`\`  
  createProject는 ~를 합니다.  
  \`### uploadProjectFiles\`  
  \`\`\`  
  [코드만]  
  \`\`\`  
  uploadProjectFiles는 ~를 합니다.

메서드가 없거나 거의 없는 파일(설정만 있는 파일 등)은 개요만 작성하고 이 섹션은 생략하거나 "해당 없음"으로 처리해도 됩니다.

- **길이 제한 (필수):** 파일당 **800자 이내**로 작성하세요. **메서드/단위는 파일당 최대 3~4개**만 골라 핵심만 설명하고, 코드 스니펫은 **5~8줄** 이내로만 넣으세요.

# 기타
- JSON 응답 시 \`markdown_content\` 안의 줄바꿈은 \\n으로 이스케이프하세요.
- **응답 완성 (필수):** 응답이 길어도 **절대 중단하지 말고**, \`file_summaries\` 배열을 **마지막 파일까지 끝까지 완성**한 뒤에만 응답을 마치세요.

# 출력 형식 (JSON)
반드시 다음 JSON 형식을 정확히 따르세요. (마크다운 없이 JSON만 반환)
- **\`file_summaries\`는 제공된 모든 파일에 대해 항목을 끝까지 채운 뒤** 응답을 종료하세요. 중간에 끊지 마세요.

{
  "file_summaries": [
    {
      "file_path": "제공된 파일 경로와 동일 (예: src/app/page.tsx)",
      "markdown_content": "설명 마크다운 전체 문자열 (줄바꿈은 \\n)"
    }
  ]
}
`;

  const userPrompt = `## 1단계 분석 결과 (주요 파일 목록)
${JSON.stringify(analysisResult.step1, null, 2)}

## 주요 파일 소스코드 (경로 -> 내용)
${JSON.stringify(fileContents, null, 2)}

## 프로젝트 파일 목록 (참고)
${JSON.stringify(project.structure, null, 2)}
`;

  return { systemPrompt, userPrompt };
};
